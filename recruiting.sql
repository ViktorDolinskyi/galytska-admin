create policy "remove" on rc_candidates for delete to authenticated using (app_level('recruit') >= 3 and rc_cand_ok(id, created_by));

create policy "read"   on rc_apps for select to authenticated using (app_level('recruit') >= 1 and rc_vac_ok(vacancy_id));
create policy "write"  on rc_apps for insert to authenticated with check (app_level('recruit') >= 2 and rc_vac_ok(vacancy_id));
create policy "update" on rc_apps for update to authenticated using (app_level('recruit') >= 2 and rc_vac_ok(vacancy_id));
create policy "remove" on rc_apps for delete to authenticated using (app_level('recruit') >= 2 and rc_vac_ok(vacancy_id) and stage <> 'hired');

create policy "read"   on rc_events for select to authenticated using (app_level('recruit') >= 1 and rc_cand_id_ok(candidate_id));
create policy "write"  on rc_events for insert to authenticated with check (app_level('recruit') >= 2 and rc_cand_id_ok(candidate_id));
create policy "remove" on rc_events for delete to authenticated using (app_level('recruit') >= 3 or created_by = auth.uid());

