create policy "write"  on rc_vacancy_pay for insert to authenticated with check (app_level('recruit') >= 2 and app_level('pay') >= 1 and rc_vac_ok(vacancy_id));
create policy "update" on rc_vacancy_pay for update to authenticated using (app_level('recruit') >= 2 and app_level('pay') >= 1 and rc_vac_ok(vacancy_id));
create policy "remove" on rc_vacancy_pay for delete to authenticated using (app_level('recruit') >= 2 and app_level('pay') >= 1 and rc_vac_ok(vacancy_id));

