create policy "write"  on rc_vacancy_ext for insert to authenticated with check (app_level('recruit') >= 2 and rc_vac_ok(vacancy_id));
create policy "update" on rc_vacancy_ext for update to authenticated using (app_level('recruit') >= 2 and rc_vac_ok(vacancy_id));
create policy "remove" on rc_vacancy_ext for delete to authenticated using (app_level('recruit') >= 2 and rc_vac_ok(vacancy_id));

