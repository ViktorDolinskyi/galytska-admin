-- ============================================================
--  Рекрутинг: заявки → вакансії → кандидати → «Прийом»
--
--  • rc_vacancies     — заявка керівника й вакансія в одному записі:
--                       draft → pending (на погодженні) → open (погоджено,
--                       у роботі) / rejected; далі paused, closed, cancelled.
--  • rc_vacancy_pay   — вилка зарплати (видно лише з дозволом «Зарплати»).
--  • rc_candidates    — база кандидатів (окремо від довідника співробітників).
--  • rc_apps          — кандидат у воронці конкретної вакансії: етап,
--                       співбесіда, пробний день, пропозиція.
--  • rc_events        — історія: зміни етапів, нотатки, відгуки керівника,
--                       відгуки з сайтів роботи (kind = applied).
--  • rc_vacancy_ext   — публікації вакансії на сайтах роботи (інтеграції).
--  • rc_hire(...)     — «Прийняти»: створює співробітника (або повертає
--                       колишнього за телефоном) і операцію «Прийом» зі
--                       статусом «На погодженні». Проводить її HR у
--                       «Кадрових операціях», як будь-яку іншу.
--  • rc_plan_check()  — чи вміщується заявка в план HR-файлу (лише
--                       попередження, заявку можна погодити й без плану).
--  • Сховище rc-files — резюме кандидатів (приватне).
--
--  Права — новий розділ «Рекрутинг» (recruit) у ролях з обсягом даних:
--    Вся компанія  — усі заявки й вакансії; лише такі користувачі
--                    погоджують заявки (власник, HR, старший рекрутер)
--    Мій підрозділ — заявки й вакансії своїх підрозділів (керівник)
--    Тільки свої   — вакансії, які людина веде або створила (рекрутер)
--  Шаблони: HR-менеджер — Повний · вся компанія; Старший рекрутер (нова
--  роль) — Повний · вся компанія; Рекрутер — Редагування · тільки свої;
--  Лінійний керівник — Редагування · мій підрозділ.
--
--  Запускати ПІСЛЯ roles_v2.sql і hr_operations.sql. Можна повторно.
-- ============================================================

do $$
begin
  if to_regprocedure('public.app_scope(text)') is null then
    raise exception 'Спершу виконай roles_v2.sql (обсяг даних у ролях)';
  end if;
  if to_regclass('public.hr_operations') is null then
    raise exception 'Спершу виконай hr_operations.sql (кадрові операції)';
  end if;
end $$;

