create policy "rc-files write"  on storage.objects for insert to authenticated with check (bucket_id = 'rc-files' and app_level('recruit') >= 2);
create policy "rc-files remove" on storage.objects for delete to authenticated using (bucket_id = 'rc-files' and app_level('recruit') >= 2);

