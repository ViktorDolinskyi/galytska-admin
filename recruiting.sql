create or replace function rc_candidates_norm() returns trigger
language plpgsql as $$
begin
  new.email := nullif(lower(btrim(new.email)), '');
  new.phone := nullif(regexp_replace(coalesce(new.phone, ''), '\D', '', 'g'), '');
  if tg_op = 'INSERT' and auth.uid() is not null then new.created_by := auth.uid(); end if;
  if tg_op = 'UPDATE' then new.created_by := old.created_by; end if;
  return new;
end $$;
