-- ---------- Функції прав ----------
-- чи бачить поточний користувач вакансію з такими полями
create or replace function rc_vrow_ok(p_unit bigint, p_recruiter uuid, p_created uuid) returns boolean
language plpgsql stable security definer set search_path = public as $$
declare s text := app_scope('recruit');
begin
  if s = 'all' then return true; end if;
  if p_created = auth.uid() or p_recruiter = auth.uid() then return true; end if;
  if s = 'unit' and p_unit is not null then return p_unit in (select app_my_units()); end if;
  return false;
end $$;

create or replace function rc_vac_ok(p_vac bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from rc_vacancies v where v.id = p_vac and rc_vrow_ok(v.unit_id, v.recruiter_id, v.created_by));
$$;

-- кандидат видно, якщо його додав цей користувач або він у видимій вакансії
-- (поле created_by передається з рядка, щоб INSERT … RETURNING бачив щойно доданого)
drop function if exists rc_cand_ok(bigint);
create or replace function rc_cand_ok(p_cand bigint, p_created uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select app_scope('recruit') = 'all'
      or p_created = auth.uid()
      or exists (select 1 from rc_apps a where a.candidate_id = p_cand and rc_vac_ok(a.vacancy_id));
$$;
create or replace function rc_cand_id_ok(p_cand bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from rc_candidates c where c.id = p_cand and rc_cand_ok(c.id, c.created_by));
$$;

-- хто може вести вакансії (для призначення): активні користувачі з «Рекрутинг» ≥ Редагування
create or replace function rc_staff() returns table (id uuid, full_name text, role_name text, scope text)
language sql stable security definer set search_path = public as $$
  select u.id, coalesce(nullif(u.full_name,''), u.email), r.name,
         case when u.is_owner or coalesce(r.is_admin,false) then 'all'
              else coalesce((select rp.scope from app_role_perms rp where rp.role_id = u.role_id and rp.section = 'recruit'),'all') end
    from app_users u left join app_roles r on r.id = u.role_id
   where app_level('recruit') >= 1 and u.is_active
     and (u.is_owner or coalesce(r.is_admin,false)
          or coalesce((select up.level from app_user_perms up where up.user_id = u.id and up.section = 'recruit'),
                      (select rp.level from app_role_perms rp where rp.role_id = u.role_id and rp.section = 'recruit'), 0) >= 2)
   order by 2;
$$;

-- дублікати за телефоном серед кандидатів і співробітників (видно лише ПІБ і стан)
create or replace function rc_phone_dupes(p_phone text, p_except bigint default null)
returns table (kind text, ref_id bigint, name text, info text)
language sql stable security definer set search_path = public as $$
  select 'candidate', c.id, concat_ws(' ', c.last_name, c.first_name),
         coalesce((select string_agg(v.position || ': ' || a.stage, ', ') from rc_apps a join rc_vacancies v on v.id = a.vacancy_id where a.candidate_id = c.id), 'без вакансії')
    from rc_candidates c
   where app_level('recruit') >= 1 and p_phone is not null and p_phone <> '' and c.phone = p_phone and c.id is distinct from p_except
  union all
  select 'employee', e.id, concat_ws(' ', e.last_name, e.first_name),
         case when e.dismissal_date is null then 'працює: ' || coalesce(e.position,'—') else 'звільнений ' || to_char(e.dismissal_date,'DD.MM.YYYY') end
    from dict_employees e
   where app_level('recruit') >= 1 and p_phone is not null and p_phone <> '' and e.phone = p_phone;
$$;

-- План HR-файлу: чи є місце під заявку. Лише попередження.
--   plan   — рядків у HR-файлі підрозділу з плановою сумою в місяці виходу
--   active — з них людей, які ще працюють
--   free   — рядки звільнених (бюджет вивільнився) мінус інші відкриті вакансії підрозділу
--   replace_ok — людина, яку замінюємо, є в плані цього місяця
create or replace function rc_plan_check(p_unit bigint, p_date date, p_qty int default 1,
                                         p_replace bigint default null, p_vac bigint default null)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare d date := coalesce(p_date, current_date); f uuid; pl int; act int; oth int; rep boolean := false;
begin
  if app_level('recruit') < 1 or p_unit is null then return null; end if;
  if to_regclass('public.hr_files') is null then return jsonb_build_object('file', false); end if;
  select id into f from hr_files where unit_id = p_unit and year = extract(year from d)::int limit 1;
  if f is null then return jsonb_build_object('file', false, 'year', extract(year from d)::int); end if;
  select count(*), count(*) filter (where e.dismissal_date is null or e.dismissal_date >= date_trunc('month', d)::date)
    into pl, act
    from (select distinct he.employee_id, coalesce(he.row_no, 0) rn
            from hr_entries he where he.hr_file_id = f and he.month = extract(month from d)::int and he.amount_plan > 0) x
    left join dict_employees e on e.id = x.employee_id;
  select coalesce(sum(qty), 0) into oth from rc_vacancies
   where unit_id = p_unit and status in ('pending','open','paused') and id is distinct from p_vac;
  if p_replace is not null then
    rep := exists (select 1 from hr_entries he where he.hr_file_id = f and he.month = extract(month from d)::int
                    and he.amount_plan > 0 and he.employee_id = p_replace);
  end if;
  return jsonb_build_object('file', true, 'month', extract(month from d)::int, 'year', extract(year from d)::int,
                            'plan', pl, 'active', act, 'other', oth, 'free', greatest(pl - act - oth, 0),
                            'replace_ok', rep, 'ok', rep or (pl - act - oth) >= coalesce(p_qty, 1));
end $$;

-- «Прийняти»: співробітник + операція «Прийом» на погодженні
create or replace function rc_hire(p_app bigint, p_start date, p_position text, p_unit bigint,
                                   p_schedule text default null, p_rate numeric default 1, p_salary numeric default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare a rc_apps; c rc_candidates; v rc_vacancies; emp bigint; ex dict_employees; op bigint; who text; no text; n int; hired int;
begin
  if app_level('recruit') < 2 then raise exception 'Немає права змінювати рекрутинг'; end if;
  select * into a from rc_apps where id = p_app for update;
  if a.id is null or not rc_vac_ok(a.vacancy_id) then raise exception 'Кандидата у вакансії не знайдено'; end if;
  if a.stage = 'hired' then raise exception 'Кандидата вже прийнято'; end if;
  if p_start is null then raise exception 'Вкажи дату виходу'; end if;
  select * into c from rc_candidates where id = a.candidate_id;
  select * into v from rc_vacancies where id = a.vacancy_id;
  select coalesce(nullif(full_name,''), email) into who from app_users where id = auth.uid();

  -- той самий телефон у довіднику: колишній співробітник повертається, чинний — помилка
  if c.employee_id is not null then select * into ex from dict_employees where id = c.employee_id; end if;
  if ex.id is null and coalesce(c.phone,'') <> '' then select * into ex from dict_employees where phone = c.phone limit 1; end if;
  if ex.id is not null then
    if ex.dismissal_date is null and exists (select 1 from hr_operations o where o.employee_id = ex.id and o.status = 'posted' and o.kind in ('hire','initial')) then
      raise exception 'Людина з цим телефоном уже працює: % %', ex.last_name, coalesce(ex.first_name,'');
    end if;
    emp := ex.id;
  else
    insert into dict_employees (last_name, first_name, patronymic, phone)
    values (c.last_name, c.first_name, c.patronymic, nullif(c.phone,''))
    returning id into emp;
  end if;

  select coalesce(max((substring(order_no from '^К-(\d+)$'))::int), 0) + 1 into n from hr_operations where order_no ~ '^К-\d+$';
  no := 'К-' || lpad(n::text, 3, '0');
  insert into hr_operations (employee_id, kind, status, effective_date, order_no, basis, note, before, after, created_by, submitted_at)
  values (emp, 'hire', 'pending', p_start, no, 'Рекрутинг: вакансія «' || v.position || '»',
          'Кандидат із рекрутингу; веде ' || coalesce(v.recruiter_name, who, '—'), '{}'::jsonb,
          jsonb_strip_nulls(jsonb_build_object('unit_id', coalesce(p_unit, v.unit_id), 'position', coalesce(nullif(p_position,''), v.position),
                                               'schedule', coalesce(nullif(p_schedule,''), v.schedule), 'rate', coalesce(p_rate, 1))),
          coalesce(who, 'рекрутинг'), now())
  returning id into op;
  if p_salary is not null and app_level('pay') >= 1 then
    insert into hr_op_pay (op_id, salary_after) values (op, p_salary);
  end if;

  update rc_apps set stage = 'hired', hr_op_id = op, employee_id = emp, offer_start = p_start, updated_at = now() where id = a.id;
  update rc_candidates set employee_id = emp where id = c.id;
  insert into rc_events (app_id, candidate_id, kind, body, author)
  values (a.id, c.id, 'hire', 'Створено «Прийом» ' || no || ' з ' || to_char(p_start, 'DD.MM.YYYY') || ' — на погодженні в «Кадрових операціях»', who);

  select count(*) into hired from rc_apps where vacancy_id = v.id and stage = 'hired';
  if hired >= v.qty and v.status in ('open','paused') then
    update rc_vacancies set status = 'closed', closed_at = now() where id = v.id;
  end if;
  return jsonb_build_object('employee_id', emp, 'op_id', op, 'order_no', no, 'closed', hired >= v.qty, 'rehire', ex.id is not null);
end $$;

-- погодити чи відхилити заявку може лише користувач з обсягом «Вся компанія»
create or replace function rc_vacancies_guard() returns trigger
language plpgsql as $$
begin
  if auth.uid() is null then return new; end if;                    -- SQL Editor / сервіс
  if tg_op = 'INSERT' then
    if new.status not in ('draft','pending') and app_scope('recruit') <> 'all' then
      raise exception 'Нова заявка може бути лише чернеткою або на погодженні';
    end if;
    new.created_by := auth.uid();
    return new;
  end if;
  if old.status in ('draft','pending','rejected') and new.status in ('open','rejected')
     and new.status is distinct from old.status and app_scope('recruit') <> 'all' then
    raise exception 'Погоджує заявки власник або HR (обсяг «Вся компанія» в рекрутингу)';
  end if;
  if new.recruiter_id is distinct from old.recruiter_id and app_scope('recruit') <> 'all' then
    raise exception 'Призначає відповідального лише старший рекрутер, HR або власник';
  end if;
  new.created_by := old.created_by;
  return new;
end $$;
drop trigger if exists rc_vacancies_guard on rc_vacancies;
create trigger rc_vacancies_guard before insert or update on rc_vacancies
  for each row execute function rc_vacancies_guard();

-- ---------- Політики ----------
do $$
declare t text; pol record;
begin
  foreach t in array array['rc_vacancies','rc_vacancy_pay','rc_vacancy_ext','rc_candidates','rc_apps','rc_events'] loop
    execute format('alter table %I enable row level security', t);
    for pol in select policyname from pg_policies where schemaname = 'public' and tablename = t loop
      execute format('drop policy %I on %I', pol.policyname, t);
    end loop;
  end loop;
end $$;

create policy "read"   on rc_vacancies for select to authenticated using (app_level('recruit') >= 1 and rc_vrow_ok(unit_id, recruiter_id, created_by));
create policy "write"  on rc_vacancies for insert to authenticated with check (app_level('recruit') >= 2 and (app_scope('recruit') <> 'unit' or unit_id in (select app_my_units())));
create policy "update" on rc_vacancies for update to authenticated using (app_level('recruit') >= 2 and rc_vrow_ok(unit_id, recruiter_id, created_by)) with check (app_level('recruit') >= 2);
create policy "remove" on rc_vacancies for delete to authenticated using (
  (app_level('recruit') >= 3 and rc_vrow_ok(unit_id, recruiter_id, created_by))
  or (app_level('recruit') >= 2 and status = 'draft' and created_by = auth.uid()));

