insert into app_role_perms (role_id, section, level, scope)
select x.role_id, 'recruit', x.lv, x.sc
  from (values ('hr', 3, 'all'), ('senior_recruiter', 3, 'all'), ('recruiter', 2, 'own'), ('line_manager', 2, 'unit')) x(role_id, lv, sc)
 where exists (select 1 from app_roles r where r.id = x.role_id)
on conflict (role_id, section) do nothing;

-- старший рекрутер: решта розділів як у рекрутера
insert into app_role_perms (role_id, section, level, scope)
select 'senior_recruiter', rp.section, rp.level, rp.scope
  from app_role_perms rp where rp.role_id = 'recruiter' and rp.section <> 'recruit'
on conflict (role_id, section) do nothing;

