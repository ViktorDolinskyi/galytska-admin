-- ============================================================
--  Картка співробітника «Досьє»: нові дані
--
--  • dict_employees: фото, теги, днів відпустки на рік
--  • emp_notes      — нотатки HR (стрічка подій)
--  • emp_documents  — документи з терміном дії (медкнижка, санмінімум…)
--  • emp_trainings  — навчання й тести (поки вручну, згодом — з Collaborator)
--  • emp_vacations  — відпустки (заплановані й минулі)
--  • сховище emp-files (приватне) — фото й файли документів
--
--  Права — як у довідника співробітників: бачить розділ «Компанія» (≥ 1),
--  додає/змінює ≥ 2, видаляє ≥ 3. Можна запускати повторно.
-- ============================================================

alter table dict_employees add column if not exists photo_path     text;
alter table dict_employees add column if not exists tags           text[] not null default '{}';
alter table dict_employees add column if not exists vacation_days  int    not null default 24;  -- днів щорічної відпустки на рік

create table if not exists emp_notes (
  id          bigint generated by default as identity primary key,
  employee_id bigint not null references dict_employees(id) on delete cascade,
  body        text   not null,
  author      text,
  created_at  timestamptz not null default now()
);
create index if not exists emp_notes_emp_idx on emp_notes(employee_id, created_at desc);

create table if not exists emp_documents (
  id          bigint generated by default as identity primary key,
  employee_id bigint not null references dict_employees(id) on delete cascade,
  title       text   not null,              -- напр., «Медична книжка»
  issued_on   date,
  expires_on  date,                         -- порожньо — безстроковий
  file_path   text,                         -- у сховищі emp-files
  file_name   text,
  created_at  timestamptz not null default now()
);
create index if not exists emp_documents_emp_idx on emp_documents(employee_id);
create index if not exists emp_documents_exp_idx on emp_documents(expires_on) where expires_on is not null;

create table if not exists emp_trainings (
  id           bigint generated by default as identity primary key,
  employee_id  bigint not null references dict_employees(id) on delete cascade,
  title        text   not null,
  link_url     text,                        -- курс або тест у Collaborator
  status       text   not null default 'planned' check (status in ('planned', 'in_progress', 'done', 'failed')),
  score        int    check (score between 0 and 100),
  completed_on date,
  created_at   timestamptz not null default now()
);
create index if not exists emp_trainings_emp_idx on emp_trainings(employee_id);

create table if not exists emp_vacations (
  id          bigint generated by default as identity primary key,
  employee_id bigint not null references dict_employees(id) on delete cascade,
  kind        text   not null default 'annual' check (kind in ('annual', 'unpaid', 'sick', 'other')),
  date_from   date   not null,
  date_to     date   not null,
  note        text,
  created_at  timestamptz not null default now(),
  check (date_to >= date_from)
);
create index if not exists emp_vacations_emp_idx on emp_vacations(employee_id, date_from);

-- ---------- Права ----------
do $$
declare t text; rd text; ed text; dl text;
begin
  if to_regprocedure('public.app_level(text)') is not null then
    rd := 'app_level(''company'') >= 1'; ed := 'app_level(''company'') >= 2'; dl := 'app_level(''company'') >= 3';
  else
    rd := 'true'; ed := 'true'; dl := 'true';
  end if;
  foreach t in array array['emp_notes', 'emp_documents', 'emp_trainings', 'emp_vacations'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "read" on %I', t);
    execute format('drop policy if exists "write" on %I', t);
    execute format('drop policy if exists "update" on %I', t);
    execute format('drop policy if exists "remove" on %I', t);
    execute format('create policy "read" on %I for select to authenticated using (%s)', t, rd);
    execute format('create policy "write" on %I for insert to authenticated with check (%s)', t, ed);
    execute format('create policy "update" on %I for update to authenticated using (%s) with check (%s)', t, ed, ed);
    execute format('create policy "remove" on %I for delete to authenticated using (%s)', t, dl);
  end loop;

  -- сховище: фото й документи співробітників (приватне, до 20 МБ)
  insert into storage.buckets (id, name, public, file_size_limit)
  values ('emp-files', 'emp-files', false, 20971520)
  on conflict (id) do update set public = false, file_size_limit = 20971520;
  drop policy if exists "emp-files read"   on storage.objects;
  drop policy if exists "emp-files insert" on storage.objects;
  drop policy if exists "emp-files update" on storage.objects;
  drop policy if exists "emp-files delete" on storage.objects;
  execute format('create policy "emp-files read" on storage.objects for select to authenticated using (bucket_id = ''emp-files'' and (%s))', rd);
  execute format('create policy "emp-files insert" on storage.objects for insert to authenticated with check (bucket_id = ''emp-files'' and (%s))', ed);
  execute format('create policy "emp-files update" on storage.objects for update to authenticated using (bucket_id = ''emp-files'' and (%s))', ed);
  execute format('create policy "emp-files delete" on storage.objects for delete to authenticated using (bucket_id = ''emp-files'' and (%s))', ed);
end $$;

-- Перевірка
select (select count(*) from dict_employees) as employees,
       (select count(*) from storage.buckets where id = 'emp-files') as storage_ready,
       to_regclass('public.emp_notes') is not null
   and to_regclass('public.emp_documents') is not null
   and to_regclass('public.emp_trainings') is not null
   and to_regclass('public.emp_vacations') is not null as tables_ready;
