  if exists (select 1 from information_schema.columns where table_name = 'app_role_perms' and column_name = 'scope') then
    insert into app_role_perms (role_id, section, level, scope)
    select x.r, x.s, x.l, 'all'
      from (values ('hostel_admin','hostel',3), ('hostel_admin','dash',1), ('hr','hostel',2)) x(r, s, l)
     where exists (select 1 from app_roles where id = x.r)
    on conflict (role_id, section) do nothing;
  else
    insert into app_role_perms (role_id, section, level)
    select x.r, x.s, x.l
      from (values ('hostel_admin','hostel',3), ('hostel_admin','dash',1), ('hr','hostel',2)) x(r, s, l)
     where exists (select 1 from app_roles where id = x.r)
    on conflict (role_id, section) do nothing;
  end if;
end $$;

