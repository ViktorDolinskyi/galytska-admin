-- ============================================================
--  Хостел: облік проживання
--
--  • hs_rooms     — кімнати (нумерація як у робочій таблиці: 101–106,
--                   201–206, 301–306), кількість ліжок, статус.
--  • hs_tariffs   — правила тарифу. Діє найконкретніше правило:
--                   кімната + тип мешканця → кімната → тип мешканця → загальне;
--                   серед однакових — з найпізнішою датою «діє з».
--                   Одиниця: за пів місяця, за місяць або за добу.
--  • hs_stays     — проживання: хто (співробітник з довідника або ПІБ
--                   майстра / гостя), кімната й ліжко, дати заїзду й виїзду,
--                   індивідуальна ставка (якщо є).
--  • hs_charges   — нарахування за період (1–15 і 16–кінець місяця) та
--                   ручні коригування (наприклад, борг на старті).
--  • hs_payments  — оплати: готівка, картка або утримання з зарплати.
--  Борг = нараховано − оплачено.
--
--  Права — новий розділ «Хостел» (hostel):
--    Перегляд     — бачить шахматку, мешканців і борги
--    Редагування  — заселяє, виселяє, нараховує, вносить оплати
--                   (комендант, бухгалтерія)
--    Повний       — ще й кімнати, тарифи й видалення записів
--  Нова роль «Комендант хостелу» (Хостел — Повний, решта — Перегляд Панелі).
--
--  Запускати після insert_access_tables.sql (є в усіх). Можна повторно.
-- ============================================================

do $$
begin
  if to_regprocedure('public.app_level(text)') is null then
    raise exception 'Спершу виконай insert_access_tables.sql (права доступу)';
  end if;
end $$;

-- ---------- Таблиці ----------
create table if not exists hs_rooms (
  id      bigint generated by default as identity primary key,
  no      text   not null unique,
  floor   int    not null default 1,
  beds    int    not null default 2 check (beds between 0 and 20),
  gender  text   not null default 'any' check (gender in ('any','m','f')),
  status  text   not null default 'active' check (status in ('active','repair','storage')),
  plan_no text,                                  -- номер на поверховому плані
  note    text,
  sort    int    not null default 0
);

create table if not exists hs_tariffs (
  id         bigint generated by default as identity primary key,
  name       text    not null,
  kind       text    check (kind in ('employee','master','guest')),  -- null = для всіх
  room_id    bigint  references hs_rooms(id) on delete cascade,       -- null = будь-яка кімната
  unit       text    not null default 'half' check (unit in ('half','month','day')),
  amount     numeric(12,2) not null check (amount >= 0),
  valid_from date    not null default date '2025-01-01',
  active     boolean not null default true,
  note       text
);

create table if not exists hs_stays (
  id          bigint generated by default as identity primary key,
  room_id     bigint not null references hs_rooms(id),
  bed_no      int    not null check (bed_no >= 1),
  kind        text   not null default 'employee' check (kind in ('employee','master','guest')),
  employee_id bigint references dict_employees(id) on delete set null,
  full_name   text   not null,
  phone       text,
  dept        text,                                -- відділ / від кого гість
  check_in    date   not null default current_date,
  check_out   date,
  rate        numeric(12,2),                       -- індивідуальна ставка (замість тарифу)
  rate_unit   text   check (rate_unit in ('half','month','day')),
  note        text,
  created_by  uuid   default auth.uid(),
  created_at  timestamptz not null default now(),
  check (check_out is null or check_out >= check_in)
);
create index if not exists hs_stays_room_idx on hs_stays(room_id, bed_no);
create index if not exists hs_stays_emp_idx  on hs_stays(employee_id);
-- на одному ліжку одночасно живе лише одна людина
create unique index if not exists hs_stays_bed_live on hs_stays(room_id, bed_no) where check_out is null;

create table if not exists hs_charges (
  id          bigint generated by default as identity primary key,
  stay_id     bigint not null references hs_stays(id) on delete cascade,
  period_from date   not null,
  period_to   date   not null,
  days        int,
  amount      numeric(12,2) not null,
  manual      boolean not null default false,      -- ручне коригування
  note        text,
  created_at  timestamptz not null default now()
);
-- автонарахування — одне на мешканця за період (ручних може бути кілька)
create unique index if not exists hs_charges_auto on hs_charges(stay_id, period_from) where not manual;

create table if not exists hs_payments (
  id          bigint generated by default as identity primary key,
  stay_id     bigint not null references hs_stays(id) on delete cascade,
  paid_on     date   not null default current_date,
  amount      numeric(12,2) not null check (amount > 0),
  method      text   not null default 'cash' check (method in ('cash','card','salary')),
  period_from date,                                -- за який період (необов'язково)
  note        text,
  created_by  uuid   default auth.uid(),
  author      text,
  created_at  timestamptz not null default now()
);
create index if not exists hs_payments_stay_idx on hs_payments(stay_id);

-- ---------- Політики ----------
do $$
declare t text; pol record;
begin
  foreach t in array array['hs_rooms','hs_tariffs','hs_stays','hs_charges','hs_payments'] loop
    execute format('alter table %I enable row level security', t);
    for pol in select policyname from pg_policies where schemaname = 'public' and tablename = t loop
      execute format('drop policy %I on %I', pol.policyname, t);
    end loop;
    execute format('create policy "read" on %I for select to authenticated using (app_level(''hostel'') >= 1)', t);
  end loop;
end $$;

-- кімнати й тарифи — лише «Повний»
create policy "write"  on hs_rooms   for insert to authenticated with check (app_level('hostel') >= 3);
create policy "update" on hs_rooms   for update to authenticated using (app_level('hostel') >= 3);
create policy "remove" on hs_rooms   for delete to authenticated using (app_level('hostel') >= 3);
create policy "write"  on hs_tariffs for insert to authenticated with check (app_level('hostel') >= 3);
create policy "update" on hs_tariffs for update to authenticated using (app_level('hostel') >= 3);
create policy "remove" on hs_tariffs for delete to authenticated using (app_level('hostel') >= 3);
-- проживання, нарахування, оплати — «Редагування»; видалення — «Повний»
create policy "write"  on hs_stays    for insert to authenticated with check (app_level('hostel') >= 2);
create policy "update" on hs_stays    for update to authenticated using (app_level('hostel') >= 2);
create policy "remove" on hs_stays    for delete to authenticated using (app_level('hostel') >= 3);
create policy "write"  on hs_charges  for insert to authenticated with check (app_level('hostel') >= 2);
create policy "update" on hs_charges  for update to authenticated using (app_level('hostel') >= 2);
create policy "remove" on hs_charges  for delete to authenticated using (app_level('hostel') >= 2);
create policy "write"  on hs_payments for insert to authenticated with check (app_level('hostel') >= 2);
create policy "update" on hs_payments for update to authenticated using (app_level('hostel') >= 3);
create policy "remove" on hs_payments for delete to authenticated using (app_level('hostel') >= 3);

