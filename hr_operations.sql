-- ============================================================
--  Кадрові операції: кадровий облік через накази
--
--  • hr_operations — кожна зміна людини: прийом, переведення, зміна
--    окладу, додаткова посада, відпустка, лікарняний, премія/стягнення,
--    зміна персональних даних, звільнення. Поточна посада, підрозділ,
--    графік і ставка = результат проведених операцій.
--  • hr_op_pay     — суми (оклад, премія) окремо: їх видно лише з
--    доступом до розділу «Бюджет».
--  • dict_employees: графік і ставка (поточний стан).
--  • Початковий стан: кожен співробітник отримує проведену операцію
--    «Початковий стан» з даних довідника (і «Звільнення», якщо звільнений).
--
--  Статуси: draft (чернетка) → pending (на погодженні) → posted
--  (проведено) → cancelled (скасовано). Проведені не видаляються, лише
--  скасовуються, щоб історія не губилась.
--
--  Права — розділ «Компанія»: бачить ≥ 1, створює й змінює ≥ 2,
--  проводить і скасовує лише «Повний» (3).
--  Можна запускати повторно.
-- ============================================================

alter table dict_employees add column if not exists schedule text;                       -- графік роботи, напр. «2/2, 12 год»
alter table dict_employees add column if not exists rate     numeric(4,2) default 1;     -- ставка (1 = повна)

create table if not exists hr_operations (
  id             bigint generated by default as identity primary key,
  employee_id    bigint not null references dict_employees(id) on delete cascade,
  kind           text   not null check (kind in ('initial','hire','transfer','pay','extra','vacation','sick','bonus','personal','dismissal')),
  status         text   not null default 'draft' check (status in ('draft','pending','posted','cancelled')),
  effective_date date   not null,              -- діє з
  end_date       date,                         -- для відпустки, лікарняного, додаткової посади
  order_no       text,                         -- номер наказу, напр. К-119
  basis          text,                         -- підстава
  note           text,
  before         jsonb  not null default '{}', -- значення до операції (посада, підрозділ, графік…)
  after          jsonb  not null default '{}', -- нові значення
  file_path      text,                         -- скан наказу у сховищі emp-files
  file_name      text,
  applied_at     timestamptz,                  -- коли зміни внесено в довідник
  vacation_id    bigint,                       -- створений запис emp_vacations
  replaces_id    bigint references hr_operations(id) on delete set null,
  cancel_reason  text,
  ack_at         timestamptz,                  -- ознайомлення в боті (згодом)
  created_by     text,
  created_at     timestamptz not null default now(),
  submitted_at   timestamptz,
  approved_by    text,
  approved_at    timestamptz,
  cancelled_by   text,
  cancelled_at   timestamptz,
  check (end_date is null or end_date >= effective_date)
);
create index if not exists hr_operations_emp_idx    on hr_operations(employee_id, effective_date);
create index if not exists hr_operations_status_idx on hr_operations(status);
create index if not exists hr_operations_date_idx   on hr_operations(effective_date desc);

create table if not exists hr_op_pay (
  op_id          bigint primary key references hr_operations(id) on delete cascade,
  salary_before  numeric(14,2),
  salary_after   numeric(14,2),               -- новий оклад
  amount         numeric(14,2)                -- сума премії / утримання
);

-- ---------- Права ----------
do $$
declare rd text; ed text; dl text; pr text; brd text; bed text;
begin
  if to_regprocedure('public.app_level(text)') is not null then
    rd  := 'app_level(''company'') >= 1'; ed := 'app_level(''company'') >= 2'; dl := 'app_level(''company'') >= 3';
    brd := 'app_level(''budget'') >= 1';  bed := 'app_level(''budget'') >= 1 and app_level(''company'') >= 2';
  else
    rd := 'true'; ed := 'true'; dl := 'true'; brd := 'true'; bed := 'true';
  end if;

  alter table hr_operations enable row level security;
  drop policy if exists "read"   on hr_operations;
  drop policy if exists "write"  on hr_operations;
  drop policy if exists "update" on hr_operations;
  drop policy if exists "remove" on hr_operations;
  execute format('create policy "read" on hr_operations for select to authenticated using (%s)', rd);
  execute format('create policy "write" on hr_operations for insert to authenticated with check (%s)', ed);
  execute format('create policy "update" on hr_operations for update to authenticated using (%s) with check (%s)', ed, ed);
  -- видалити можна лише чернетку або операцію на погодженні
  execute format('create policy "remove" on hr_operations for delete to authenticated using ((%s) and status in (''draft'',''pending''))', dl);

  alter table hr_op_pay enable row level security;
  drop policy if exists "read"   on hr_op_pay;
  drop policy if exists "write"  on hr_op_pay;
  drop policy if exists "update" on hr_op_pay;
  drop policy if exists "remove" on hr_op_pay;
  execute format('create policy "read" on hr_op_pay for select to authenticated using (%s)', brd);
  execute format('create policy "write" on hr_op_pay for insert to authenticated with check (%s)', bed);
  execute format('create policy "update" on hr_op_pay for update to authenticated using (%s) with check (%s)', bed, bed);
  execute format('create policy "remove" on hr_op_pay for delete to authenticated using (%s)', bed);
end $$;

-- Провести або скасувати може лише рівень «Повний» у «Компанії»;
-- проведену операцію не можна повернути в чернетку чи змінити її суть.
create or replace function hr_operations_guard() returns trigger
language plpgsql as $$
begin
  if to_regprocedure('public.app_level(text)') is null or auth.uid() is null then
    return new;                                         -- без системи прав або service_role (бот)
  end if;
  if new.status is distinct from old.status and new.status in ('posted','cancelled')
     and app_level('company') < 3 then
    raise exception 'Провести або скасувати операцію може лише користувач з повним доступом до розділу «Компанія»';
  end if;
  if old.status = 'posted' and new.status not in ('posted','cancelled') then
    raise exception 'Проведену операцію не можна повернути в чернетку — скасуй її';
  end if;
  if old.status in ('posted','cancelled') and (new.kind, new.employee_id, new.effective_date, new.after)
       is distinct from (old.kind, old.employee_id, old.effective_date, old.after) then
    raise exception 'Проведену або скасовану операцію змінювати не можна — створи нову';
  end if;
  return new;
end $$;
drop trigger if exists hr_operations_guard on hr_operations;
create trigger hr_operations_guard before update on hr_operations
  for each row execute function hr_operations_guard();

-- ---------- Початковий стан з довідника ----------
insert into hr_operations (employee_id, kind, status, effective_date, after, note, applied_at, approved_at, created_by)
select e.id, 'initial', 'posted', coalesce(e.hire_date, current_date),
       jsonb_strip_nulls(jsonb_build_object('unit_id', e.primary_unit_id, 'position', e.position)),
       'Початковий стан, перенесено з довідника', now(), now(), 'система'
from dict_employees e
where not exists (select 1 from hr_operations o where o.employee_id = e.id);

insert into hr_operations (employee_id, kind, status, effective_date, after, note, applied_at, approved_at, created_by)
select e.id, 'dismissal', 'posted', e.dismissal_date,
       jsonb_build_object('dismissal_date', e.dismissal_date),
       'Перенесено з довідника', now(), now(), 'система'
from dict_employees e
where e.dismissal_date is not null
  and not exists (select 1 from hr_operations o where o.employee_id = e.id and o.kind = 'dismissal');

-- Перевірка
select (select count(*) from dict_employees)                         as employees,
       (select count(*) from hr_operations where kind = 'initial')   as initial_ops,
       (select count(*) from hr_operations where kind = 'dismissal') as dismissals,
       to_regclass('public.hr_op_pay') is not null                   as pay_ready;
